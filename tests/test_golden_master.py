@pytest.mark.fast
def test_structural_mlt_nabla_alpha_is_differentiable():
    """Assert alpha_mlt is LIVE in mlt_nabla's gradient (not static/stop_gradient'd).

    A refactor that accidentally makes alpha_mlt a static arg (e.g. bundled into
    a meta_field of a frozen config) or wraps it in stop_gradient would make this
    gradient exactly zero. This test catches that: it evaluates at a genuinely
    SUPERADIABATIC operating point (efficient convection, low density) where alpha
    materially controls the temperature gradient, so ∂nabla/∂alpha is a robust
    ~1e-2 (NOT the ~1e-9 numerical floor you get at a barely-convective point) —
    and asserts it is finite AND meaningfully nonzero.

    NOTE (verified 2026-09-10): at the earlier operating point (T=1e6,P=1e16,
    rho=0.5) mlt_nabla sits on the adiabatic floor (returns nad=0.4) and ∂/∂alpha
    is ~1e-9 — indistinguishable from a static-zero gradient, so a nonzero check
    there was impossible. This point (T=1e5,P=1e8,rho=1e-5,kappa=100,nabla_rad=10)
    gives nabla≈0.411 (above the 0.4 floor) and ∂/∂alpha≈-7.9e-3.
    """
    from stellar_jax.transport.mlt import mlt_nabla
    from stellar_jax.config.constants import G, Msun, Rsun

    # Superadiabatic, low-density point: MLT is efficient, alpha matters.
    nabla_rad = jnp.float64(10.0)
    nad = jnp.float64(0.4)
    T = jnp.float64(1e5)
    P = jnp.float64(1e8)
    rho = jnp.float64(1e-5)
    kappa = jnp.float64(100.0)
    g = jnp.float64(G * Msun / Rsun**2)
    mu = jnp.float64(0.62)

    def nabla_of_alpha(a):
        return mlt_nabla(nabla_rad, nad, T, P, rho, kappa, g, mu, a)

    val = float(nabla_of_alpha(jnp.float64(1.9)))
    grad_val = float(jax.grad(nabla_of_alpha)(jnp.float64(1.9)))

    # Sanity: we're genuinely off the adiabatic floor (else the test is vacuous).
    assert val > float(nad) + 1e-4, (
        f"mlt_nabla is on the adiabatic floor here (nabla={val} ≈ nad={float(nad)}); "
        "the structural test needs a superadiabatic point where alpha matters.")
    assert np.isfinite(grad_val), "mlt_nabla gradient w.r.t. alpha is not finite"
    # The real guard: alpha must be a LIVE input. A static/stop_gradient'd alpha
    # gives exactly 0.0 here (where a live alpha gives ~1e-2).
    assert abs(grad_val) > 1e-6, (
        f"∂nabla/∂alpha = {grad_val:.3e} ≈ 0 at a superadiabatic point where alpha "
        "MUST matter — alpha_mlt was made static / stop_gradient'd by a refactor "
        "(the silent-zero-gradient bug).")


@pytest.mark.fast
def test_structural_cell_residual_differentiable_params():
    """Assert that key physics params flow through _cell_residual's gradient.

    Verifies that y_k, y_kp1, X_mid, Z, and alpha_mlt are all in the
    differentiable path (gradient is finite and not NaN).
    """
    from stellar_jax.solver.residual import _cell_residual
    from stellar_jax.config.constants import Msun, Rsun, Lsun

    r_inner = 0.3 * Rsun
    r_outer = 0.35 * Rsun
    y_k = jnp.array([np.log(r_inner), np.log(10**(16.5)), np.log(10**(7.0)), 0.8])
    y_kp1 = jnp.array([np.log(r_outer), np.log(10**(16.3)), np.log(10**(6.95)), 0.85])
    dm = jnp.float64(0.05 * Msun)
    m_mid = jnp.float64(0.325 * Msun)
    M_star = jnp.float64(1.0 * Msun)
    X_mid = jnp.float64(0.70)
    Z = jnp.float64(0.014)
    alpha_mlt = jnp.float64(1.9)

    # Check gradient w.r.t. y_k (sum of residuals → scalar)
    def residual_sum_yk(yk):
        return jnp.sum(_cell_residual(yk, y_kp1, dm, m_mid, M_star, X_mid, Z, alpha_mlt))

    g_yk = jax.grad(residual_sum_yk)(y_k)
    assert jnp.all(jnp.isfinite(g_yk)), "cell_residual gradient w.r.t. y_k has non-finite elements"

    # Check gradient w.r.t. alpha_mlt
    def residual_sum_alpha(a):
        return jnp.sum(_cell_residual(y_k, y_kp1, dm, m_mid, M_star, X_mid, Z, a))

    g_alpha = jax.grad(residual_sum_alpha)(alpha_mlt)
    assert jnp.isfinite(g_alpha), "cell_residual gradient w.r.t. alpha_mlt is not finite"


