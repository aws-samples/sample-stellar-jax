    coeffs = grid_data['coeffs']
    x_grid = grid_data['x_grid']
    sigma2_converged = info['sigma2']
    x_steps = info['x_steps']
    h_steps = info['h_steps']
    factor = info['factor']

    # AD: get ∂σ²/∂coeffs via the custom_vjp
    _, vjp_fn = jax.vjp(
        lambda c, xg, s2: eigenfreq_radial(c, xg, s2, x_steps, h_steps, factor),
        coeffs, x_grid, sigma2_converged
    )
    g_coeffs_ad, g_x_grid_ad, _ = vjp_fn(jnp.float64(1.0))

    # FD: perturb one coefficient element and re-solve for σ² via IFT formula
    # IFT: ∂σ²/∂c_ij = −(∂D/∂c_ij) / (∂D/∂σ²)
    dD_dsigma2 = jax.grad(_radial_det_for_grad, argnums=0)(
        sigma2_converged, coeffs, x_grid, x_steps, h_steps)

