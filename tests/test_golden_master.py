    # Compare AD cotangent at (i,j) to FD
    dsigma2_dc_ad = float(g_coeffs_ad[i, j])
    np.testing.assert_allclose(
        dsigma2_dc_ad, float(dsigma2_dc_fd), rtol=1e-3,
        err_msg=f"eigenfreq_radial IFT adjoint disagrees with FD at coeffs[{i},{j}]"
    )


