@pytest.mark.fast
def test_golden_eigenfreq_from_fgong():
    """Pin σ²(l=0) from a fixed FGONG file.

    Quantity pinned: sigma2 (dimensionless eigenfrequency squared) for the
    lowest l=0 mode in the [2500, 3500] μHz bracket.
    Source: data/mesa_comparison/profiles/1.0Msun/midMS.FGONG.gz
    Tolerance: exact f64 match (deterministic Brent root + RK4 integration).
    """
    import stellar_jax.oscillations as oscillations
    import stellar_jax.oscillations as osc_mod

    ref = _load_ref()

    # Load a fixed FGONG (the midMS 1.0 M_sun profile)
    fgong_path = os.path.join(
        os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
        "data", "mesa_comparison", "profiles", "1.0Msun", "midMS.FGONG.gz"
    )
    if not os.path.isfile(fgong_path):
        pytest.skip(f"FGONG reference not found: {fgong_path}")

    # Decompress and read
    import tempfile
    with gzip.open(fgong_path, 'rt') as gz:
        content = gz.read()
    with tempfile.NamedTemporaryFile(mode='w', suffix='.FGONG', delete=False) as tmp:
        tmp.write(content)
        tmp_path = tmp.name

    try:
        glob, var = oscillations.read_fgong(tmp_path)
    finally:
        os.unlink(tmp_path)

    # Compute l=0 eigenfrequency in the solar-like range
    result = osc_mod.compute_eigenfreq_differentiable(
        glob, var, l=0, nu_min=2500.0, nu_max=3500.0
    )

    sigma2 = float(result['sigma2'])

    np.testing.assert_allclose(
        sigma2, float(ref['eigenfreq_sigma2']), atol=0, rtol=1e-9,
        err_msg="eigenfreq σ²(l=0) changed — refactor broke oscillation solver"
    )


