# ===========================================================================
# §0. REUSABLE STRUCTURAL HELPER FOR THE REFACTOR BATCHES (//)
# ===========================================================================
# The per-function structural guard against the silent-zero-gradient bug.
#
# THE BUG IT CATCHES: when a refactor bundles a function's loose args into a
# frozen pytree config (register_dataclass with data_fields vs meta_fields, or a
# NamedTuple/dataclass), it is easy to put a DIFFERENTIATED array into a
# meta_field (static) by mistake. The function still runs and returns the right
# VALUE, but jax.grad through it is now silently ZERO for that param — a forward
# value-golden will NOT catch it. A pytree-leaf assertion does: a differentiated
# param MUST flatten to a leaf; a static param does not.
#
# HOW THE BATCHES USE IT: after bundling fn's args into `config`, call
#   assert_differentiable_leaves(config, ["alpha_mlt", "Z", "M_star", ...])
# listing every field that USED to be a differentiated argument. If any is now
# static (not a leaf), this raises — before the bad gradient reaches production.
#
# WHY IT SCALES: pure pytree flatten, no compile, milliseconds — so the batches
# can call it once PER refactored function (all 169), unlike the heavy value/grad
# goldens which only cover ~5 representatives.
# ===========================================================================


def assert_differentiable_leaves(config, expected_leaf_params, *, allow_missing=False):
    """Assert each named differentiated param is a LEAF (not static) in `config`.

    Args:
        config: the frozen-pytree config object produced by a bundling refactor
            (a registered dataclass / NamedTuple / any registered pytree).
        expected_leaf_params: iterable of attribute names that were differentiated
            arguments before the refactor and MUST remain pytree leaves after it.
        allow_missing: if True, a name that is not an attribute of `config` is
            skipped (default False → a missing name is an error, since it usually
            means the field was renamed or dropped by the refactor).

    Raises:
        AssertionError: if any expected param is absent (unless allow_missing) or
            is not a leaf of the flattened pytree (i.e. was made static/meta).

    This is the structural half of the refactor net (the value/grad goldens are
    the numerical half). It has no JAX compile cost.
    """
    import jax.tree_util as jtu

    # Identity of each leaf, so we can test membership without relying on == of
    # arrays (which is ambiguous). Leaves are the differentiable payload; anything
    # in a meta_field/static slot is NOT in this list.
    leaves = jtu.tree_leaves(config)
    leaf_ids = {id(x) for x in leaves}

    missing = []
    static = []
    for name in expected_leaf_params:
        if not hasattr(config, name):
            if allow_missing:
                continue
            missing.append(name)
            continue
        val = getattr(config, name)
        if id(val) not in leaf_ids:
            static.append(name)

    problems = []
    if missing:
        problems.append(
            f"missing from config (renamed/dropped by refactor?): {missing}")
    if static:
        problems.append(
            f"present but NOT a pytree leaf — made static/meta by the refactor, "
            f"so jax.grad w.r.t. it is now SILENTLY ZERO: {static}")
    assert not problems, (
        f"assert_differentiable_leaves failed for {type(config).__name__}: "
        + "; ".join(problems)
        + f".\nFlattened leaves count={len(leaves)}. Every differentiated arg "
        "must remain a data_field/leaf, never a meta_field/static.")


# ===========================================================================
# §1. COMPOSITION OPERATOR PINS (fast, no evolve_star)
# ===========================================================================
# These test burn_cno, mix_composition, and diffuse_composition on FIXED
# synthetic inputs. They run in <5s (no JIT compilation of the full solver).
# Tolerance: exact f64 match (atol=0) — these are pure array operations with
# no stochastic element.
# ===========================================================================


def _make_synthetic_shell_data():
    """Create a fixed synthetic shell_data array for composition tests.

    Shell_data layout (from henyey.py:2753 extract_shell_data_from_henyey):
      col 0: eps (nuclear energy generation rate, erg/g/s)
      col 1: q (mass fraction coordinate, m/M_star)
      col 2: nabla_rad (radiative temperature gradient)
      col 3: nabla_ad (adiabatic temperature gradient)
      col 4: Hp/R (pressure scale height / stellar radius)
      col 5: dm/dr normalized (= dm_dr * R_star / M_star)
      col 6: log10(T)  [K]
      col 7: log10(rho) [g/cm³]
      col 8: nabla (actual temperature gradient, including MLT)
      col 9: log10(P) [dyne/cm²]

    The array is in SURFACE-TO-CENTER order (index 0 = surface, index -1 = center),
    matching extract_shell_data_from_henyey which returns shell_data[::-1] (i.e.
    reverses the center-to-surface Henyey mesh to surface-to-center).

    We create a physically-reasonable 200-zone solar interior profile.
    burn_cno and diffuse_composition read cols 6,7 as logT/logrho; mix_composition
    reads cols 1-5. Getting this layout right is critical — a wrong column mapping
    produces NaN in diffusion (logT interpreted as raw density → T=10^150).
    """
    from stellar_jax.config.mesh_defaults import N_COMP, COMP_MFRACS

    n = N_COMP  # 200 zones

    # Mass fraction: use COMP_MFRACS (center-to-surface, q^3 spacing)
    # The Henyey mesh is surface-to-center after the [::-1] reversal in
    # extract_shell_data_from_henyey, but COMP_MFRACS goes 0→1 (center→surface).
    # The composition ops sort/interp using mf_shells anyway, so the ordering
    # within shell_data doesn't matter as long as mf is monotonic somewhere.
    mf = np.array(COMP_MFRACS)  # 0 (center) → 1 (surface)

    # col 0: eps_nuc (nuclear energy generation, erg/g/s)
    # ~10 erg/g/s at center (PP chain), ~0 at surface
    eps_nuc = 10.0 * np.exp(-mf / 0.05)  # concentrated in core

    # col 2,3: nabla_rad and nabla_ad
    nabla_ad = np.full(n, 0.4)  # ideal-gas nad
    # Convective core (nabla_rad > nabla_ad) for inner ~10% by mass
    nabla_rad = np.where(mf < 0.10, 0.8, 0.25)

    # col 4: Hp/R (pressure scale height / radius)
    hp_over_R = 0.1 * (1.0 - mf) + 0.01

    # col 5: dm/dr normalized
    dm_dr_norm = np.ones(n) * 3.0

    # col 6: log10(T) — core ~1.5e7 K (logT=7.17), surface ~6000 K (logT=3.78)
    logT = np.linspace(7.17, 3.78, n)

    # col 7: log10(rho) — core ~150 g/cm³ (logrho=2.18), surface ~1e-7 (logrho=-7)
    logrho = np.linspace(2.18, -7.0, n)

    # col 8: nabla (actual temperature gradient — equals nabla_ad in CZ, nabla_rad outside)
    nabla = np.where(mf < 0.10, nabla_ad, nabla_rad)

    # col 9: log10(P) — core ~2e17 (logP=17.3), surface ~1e5 (logP=5.0)
    logP = np.linspace(17.3, 5.0, n)

    shell_data = np.column_stack([eps_nuc, mf, nabla_rad, nabla_ad, hp_over_R,
                                  dm_dr_norm, logT, logrho, nabla, logP])
    return shell_data.astype(np.float64)


@pytest.mark.fast
def test_golden_burn_cno():
    """Pin burn_cno output on fixed synthetic inputs.

    Quantity pinned: (C12_out, C13_out, N14_out) arrays (N_COMP=200 each).
    Config: dt=2e6 yr (in seconds), uniform initial CNO from Z=0.014.
    Tolerance: exact f64 match (deterministic pure-JAX computation).
    """
    import stellar_jax.evolution as evolution
    from stellar_jax.config.constants import SECONDS_PER_YEAR
    from stellar_jax.config.mesh_defaults import N_COMP, COMP_MFRACS

    ref = _load_ref()

    # Fixed inputs
    Z = 0.014
    X = np.full(N_COMP, 0.7)  # uniform hydrogen
    C12_init = np.full(N_COMP, 0.142 * Z)  # solar C12/Z ratio
    C13_init = np.full(N_COMP, 0.0036 * Z)  # solar C13/Z ratio
    N14_init = np.full(N_COMP, 0.049 * Z)  # solar N14/Z ratio
    shell_data = _make_synthetic_shell_data()
    dt = 2e6 * SECONDS_PER_YEAR  # 2 Myr in seconds

    # Run
    C12_out, C13_out, N14_out = evolution.burn_cno(
        jnp.array(C12_init), jnp.array(C13_init), jnp.array(N14_init),
        jnp.array(X), jnp.array(shell_data), jnp.float64(dt)
    )

    # Pin
    np.testing.assert_allclose(
        np.array(C12_out), ref['burn_cno_C12'], atol=0, rtol=0,
        err_msg="burn_cno C12 output changed — refactor broke behavior"
    )
    np.testing.assert_allclose(
        np.array(C13_out), ref['burn_cno_C13'], atol=0, rtol=0,
        err_msg="burn_cno C13 output changed — refactor broke behavior"
    )
    np.testing.assert_allclose(
        np.array(N14_out), ref['burn_cno_N14'], atol=0, rtol=0,
        err_msg="burn_cno N14 output changed — refactor broke behavior"
    )


