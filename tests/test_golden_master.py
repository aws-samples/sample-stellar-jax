# An AD-vs-FD check_grads provides an INDEPENDENT oracle — the golden only
# proves "same as before", but check_grads proves "AD = truth".
# ===========================================================================


@pytest.mark.fast
def test_mlt_nabla_ad_vs_fd():
    """AD-vs-FD cross-check for mlt_nabla w.r.t. alpha_mlt.

    WHAT: verifies that the custom_jvp gradient in _mlt_switch matches
    a central finite-difference at the same operating point.
    WHY: an independent oracle — if the custom_jvp sigmoid drifts or the
    cubic solve changes, the AD and FD will disagree.
    REFERENCE: finite-difference (central, eps=1e-4) — independent.
    TOLERANCE: rtol=1e-3 (first-order central FD at eps=1e-4 gives O(eps²)=1e-8
    truncation error; the comparison is limited by the FD accuracy).
    """
    from stellar_jax.transport.mlt import mlt_nabla
    from stellar_jax.config.constants import G, Msun, Rsun

    nabla_rad = jnp.float64(0.6)
    nad = jnp.float64(0.4)
    T = jnp.float64(1e6)
    P = jnp.float64(1e16)
    rho = jnp.float64(0.5)
    kappa = jnp.float64(1.0)
    g = jnp.float64(G * Msun / Rsun**2)
    mu = jnp.float64(0.62)
    alpha_mlt = jnp.float64(1.9)

    def nabla_of_alpha(a):
        return mlt_nabla(nabla_rad, nad, T, P, rho, kappa, g, mu, a)

    # AD gradient
    grad_ad = float(jax.grad(nabla_of_alpha)(alpha_mlt))

    # Central finite-difference
    eps = 1e-4
    f_plus = float(nabla_of_alpha(alpha_mlt + eps))
    f_minus = float(nabla_of_alpha(alpha_mlt - eps))
    grad_fd = (f_plus - f_minus) / (2 * eps)

    # The gradient is tiny (~1e-10) at this operating point (barely convective,
    # right at the Schwarzschild boundary). Use absolute tolerance for small values.
    np.testing.assert_allclose(
        grad_ad, grad_fd, atol=1e-12, rtol=1e-3,
        err_msg="mlt_nabla AD gradient disagrees with central FD"
    )


