"""Golden-master characterization tests for the stellar-jax refactor epic (#476).

PURPOSE: These tests pin the EXACT numerical output of the current code at fixed
configs. They are NOT physics validation tests (those live in tests/test_*.py per module). They
are REFACTOR GUARDS: if any of these change, the refactor introduced a behavioral
change — which must be investigated (either the refactor has a bug, or the test
needs re-baselining with justification).

DESIGN (docs/design/refactor-epic-report.md §3.1):
- All tests use fixed_dt to eliminate adaptive-dt nondeterminism.
- Exact f64 match (atol=0, rtol=0) for composition ops (pure array ops, deterministic).
- evolve_star + gradient + eigenfreq outputs go through XLA compilation, whose
  float-operation ORDER shifts across refactors / JAX versions, drifting results by
  ~1e-7 (physically negligible — physics is validated at <0.10 dex, i.e. ~20%). A
  bit-level pin (rtol=1e-12) therefore flagged benign reorders as "behavior changes"
  and forced a manual re-baseline on every refactor. These are now pinned at
  atol=1e-8, rtol=1e-5 (still 4-5 orders tighter than physics validation, so a REAL
  regression — which is percent-level — is still caught, while benign float
  reordering is tolerated). eigenfreq uses rtol=1e-9.
  Incident (2026-08-13): the #469 diffusion_factor knob (a default-1.0 differentiable
  input) drifted the M=1.0 log_L golden by 2.8e-7, which the old 1e-12 pin failed —
  after the validate.py>1MiB CI-discovery bug had kept this test from running on the
  intervening refactor merges. See project.md steering.

REFERENCE VALUES: Generated by `scripts/generate_golden_master.py` and committed
as `tests/golden_master_ref.npz`. The generation script records the exact output
of the current code (main HEAD at the time of creation). Re-baselining requires
running the script again and committing the updated .npz.

MARKS + CI ROUTING (updated 2026-09-10, #1113 in-house rework):
- @pytest.mark.fast: composition ops + oscillation + mlt_nabla/cell_residual value pins
  + AD-vs-FD + STRUCTURAL pytree asserts (no evolve_star, <10s each). These run PER-WAVE.
  They are the actual refactor guards: value pins catch a changed number, structural asserts
  catch the silent-zero-gradient bug (an arg wrongly made static/nondiff after bundling).
- @pytest.mark.suspended: the HEAVY value+gradient goldens (forward evolve, ∂logL/∂M,
  ∂logTe/∂α, seismic ∂σ²/∂M, the custom_vjp cotangent pins, one-step evolve, evolve_solar).
  Each compiles a full forward/backward pass (~10-40 min, up to the 120 GB CI tier). They are
  the refactor TRANSITION oracle — run ON-DEMAND during the #785 batches (locally or via a
  standalone run), and NIGHTLY — NOT on every per-wave CI (a permanent heavy per-wave cost for
  a transition-only net is the wrong trade; this is the fix that superseded PR#1120). The
  golden VALUES are committed in golden_master_ref.npz and stay valid; re-enabling per-wave is
  a one-line mark flip if ever wanted.

REFACTOR DISCIPLINE (the three rules that keep a bit-identity refactor honest):
1. If you have to LOOSEN a tolerance or EDIT a golden/gate to make it pass, that is NOT a
   refactor — STOP. A bit-identity refactor changes no number; a moved number is a bug (or a
   deliberate, separately-justified behavioral change that must be documented + re-baselined).
2. COMMIT PER FUNCTION. Each bundled/split function is its own commit so a golden/gradient
   regression bisects to ONE function, not a blended diff.
3. Golden churn is a REVIEWER RED FLAG. Re-baselining requires re-running
   scripts/generate_golden_master.py with a commit message that says WHAT changed and WHY.
   An unexplained .npz change in a "pure refactor" PR means the refactor moved behavior.

HELPER FOR THE BATCHES: assert_differentiable_leaves(...) (below, §0) — the per-function
structural guard the #1114/#1115/#1116 batches call after bundling a function's args into a
frozen pytree config, to prove each differentiated param is still a live pytree LEAF (not
static). Near-free (@fast, no compile) so it scales to all 169 refactored functions.
"""

